def dist(a, b, c, d):
    return math.hypot(a - c, (b - d) * math.cos(math.radians(a)))
# Known places whose ward the point data does not settle on its own: (state, place) -> (LGA, ward)
OVERRIDE = {("kano", "Sabon Gari Market, Kano"): ("Fagge", "Sabongari West"), ("kaduna", "Ungwan Rimi"): ("Kaduna North", "Unguwan Sarki")}
rows = []
for ss, name, kind, la, lo in LANDMARKS:
    cand = [w for w in wards if w[0] == ss]
    if (ss, name) in OVERRIDE:
        cand = [w for w in cand if (w[1], w[2]) == OVERRIDE[(ss, name)]]
        assert cand, name
    # A ward named in the place's own name wins ("Kawo Market" -> Kawo ward); otherwise the nearest ward point
    words = slugify(name.split(",")[0]).split("-")
    named = [w for w in cand if slugify(w[2]) and all(t in words for t in slugify(w[2]).split("-")) and dist(la, lo, w[3], w[4]) < 0.14]  # within ~15 km
    w = min(named or cand, key=lambda w: dist(la, lo, w[3], w[4]))
    rows.append([name, kind, ss, w[1], w[2], w[5].split("/")[-1]])
