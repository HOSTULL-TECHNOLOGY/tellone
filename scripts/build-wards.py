"""Builds src/data/wards.ts and src/data/landmarks.ts for the ward finder (careers / ward leaders).

Source: Nigeria GeoJSON data by temikeezy (MIT licence), https://github.com/temikeezy/nigeria-geojson-data
(data/full.json: 37 states, 774 LGAs, 8,809 wards with a point coordinate each), which follows INEC's ward list.
State coordinators must confirm every ward before launch (CAR-18).

Demo statuses: the number of wards that already have a leader in each region is exactly the sample in the
Careers Landing Page document (3,154 of 8,809). Which wards are filled is a stable hash, so it never changes
between builds.
   usage: python3 scripts/build-wards.py path/to/full.json
"""
import hashlib, json, math, re, sys, unicodedata

src = json.load(open(sys.argv[1], encoding="utf-8"))
STATE_SLUG = {"Federal Capital Territory": "fct", "Nassarawa": "nasarawa"}
ZONE = {}
for line in open("src/data/states.ts", encoding="utf-8"):
    m = re.search(r'slug: "([^"]+)", name: "[^"]+", capital: "[^"]+", zone: "([^"]+)"', line)
    if m:
        ZONE[m.group(1)] = m.group(2)
REGION_FILLED = {"North West": 702, "South West": 640, "South South": 488, "North Central": 495, "South East": 441, "North East": 388}
SAMPLE_FILLED = 3154

def slugify(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def h(s):
    return int(hashlib.sha1(s.encode()).hexdigest()[:8], 16)

wards = []  # (state, lga, ward, lat, lon, id)
for st in src:
    ss = STATE_SLUG.get(st["state"], slugify(st["state"]))
    assert ss in ZONE, st["state"]
    for lg in st["lgas"]:
        seen = {}
        for w in lg["wards"]:
            base = f'{ss}/{slugify(lg["name"])}/{slugify(w["name"]) or "ward"}'
            seen[base] = seen.get(base, 0) + 1
            wid = base if seen[base] == 1 else f"{base}-{seen[base]}"
            wards.append((ss, lg["name"].strip(), w["name"].strip(), round(w["latitude"], 4), round(w["longitude"], 4), wid))
assert len(wards) == 8809, len(wards)

# Status: 1 = has a leader, 2 = open and nobody from the street has joined yet, 0 = open
status = {}
for z, n in REGION_FILLED.items():
    zw = sorted([w for w in wards if ZONE[w[0]] == z], key=lambda w: h("filled:" + w[5]))
    for i, w in enumerate(zw):
        status[w[5]] = 1 if i < n else (2 if h("street:" + w[5]) % 100 < 22 else 0)
assert sum(1 for v in status.values() if v == 1) == SAMPLE_FILLED

by_state = {}
for ss, lga, ward, la, lo, wid in wards:
    by_state.setdefault(ss, {}).setdefault(lga, []).append([ward, round(la * 1e4), round(lo * 1e4), status[wid], wid.split("/")[-1]])
out = {s: [[lga, ws] for lga, ws in sorted(l.items())] for s, l in sorted(by_state.items())}
with open("src/data/wards.ts", "w", encoding="utf-8") as f:
    f.write("/**\n * All 8,809 electoral wards: state slug -> [LGA, [ward, lat×10⁴, lon×10⁴, status, ward slug][]][].\n")
    f.write(" * Generated by scripts/build-wards.py from the MIT-licensed Nigeria GeoJSON data (temikeezy/nigeria-geojson-data),\n")
    f.write(" * which follows INEC's ward list. Status (DEMO): 0 open, 1 has a leader, 2 open and nobody from the area has joined yet.\n")
    f.write(" * Loaded on demand by the ward finder (dynamic import), so it never weighs down the page. Do not edit by hand.\n */\n")
    f.write("export type WardRow = [name: string, lat: number, lon: number, status: 0 | 1 | 2, slug: string];\n")
    f.write("export const WARD_DATA: Record<string, [lga: string, wards: WardRow[]][]> = ")
    f.write(json.dumps(out, ensure_ascii=False, separators=(",", ":")))
    f.write(";\n")

